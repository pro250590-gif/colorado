/* ==========================================================================
   ЯЗЫКИ: СЛОВАРЬ И ФУНКЦИЯ t()

   Её задача 06.08.2026 и её же требование к качеству: не «перевести с
   русского», а НАПИСАТЬ по-английски так, как пишут носители. Поэтому здесь не
   построчный перевод, а нормальные английские фразы — местами короче русских,
   местами построенные иначе.

   ⚠️ ПОЧЕМУ КЛЮЧ — САМА РУССКАЯ ФРАЗА, А НЕ ПРИДУМАННЫЙ КОД.
   В index.html текст вшит прямо в разметку (`'<b>Откуда вы летите?</b>'`).
   Придумывать каждому куску имя вроде `air.title` — это переписать тысячи
   склеек и на каждой рискнуть опечаткой. Ключом взята сама строка: тогда
   перенос — это обернуть её в t(), и всё.

   ⚠️ ГЛАВНОЕ СВОЙСТВО: НЕТ ПЕРЕВОДА — ОСТАЁТСЯ РУССКИЙ. Сайт не может сломаться
   от того, что фразу ещё не перевели: она просто покажется как была. Поэтому
   переносить можно кусками, а не всё разом.

   Как добавить язык: положить рядом файл lang-<код>.js по образцу lang-en.js.
   Ничего в index.html при этом трогать не надо — ни строки (правило 22б).
   Здесь остался только МЕХАНИЗМ: сами переводы уехали в файлы языков, чтобы
   русский посетитель не качал чужие словари (шаг 2 плана, 08.08.2026).

   Что НЕ переводим (правило 10 в ROUTE-RULES.md): названия мест, рестораны,
   экскурсии, поисковые строки. Они живут в оригинале на языке страны.

   Сколько осталось:  node i18n-scan.js
   ========================================================================== */
(function (root, factory) {
  var api = factory(root);
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.I18N = api;
}(typeof self !== 'undefined' ? self : this, function (root) {

  /* ══════════════════════════════════════════════════════════════════════
     ⚠️ САМИ СЛОВАРИ ЛЕЖАТ ОТДЕЛЬНЫМИ ФАЙЛАМИ — lang-en.js, lang-<код>.js
     (шаг 2 плана, 08.08.2026)

     Здесь остался только МЕХАНИЗМ и русская запись календаря: русский — язык
     оригинала, он нужен всегда. Раньше все переводы лежали в этом файле, он
     весил 100 КБ, и качал их КАЖДЫЙ посетитель — включая русского, которому
     английские фразы не нужны вовсе. На трёх языках это втрое, и платят все.
     Приём тот же, что уже принят для текста маршрутов (правило 22г):
     язык платит за себя сам.

     Как словарь языка сюда попадает:
       · в браузере — страница подставляет lang-<код>.js, когда язык не русский,
         и файл сам зовёт I18N.add(). Приехал раньше нас — оставляет себя на
         окне (__i18nPacks), и мы подбираем его при запуске;
       · в терминале — читаем все файлы lang-*.js рядом с собой, чтобы проверкам
         и сборке был виден полный набор языков.
     ══════════════════════════════════════════════════════════════════════ */
  var DICT = {};        /* целые фразы:  язык → { русская фраза: перевод } */


  /* ══════════════════════════════════════════════════════════════════════
     СЛОВАРЬ ДЛЯ КОДА: КУСКИ, СКЛЕЕННЫЕ С ЧИСЛОМ ИЛИ С ИМЕНЕМ

     Зачем отдельно от DICT. DICT работает по готовой странице и меняет ЦЕЛЫЙ
     кусок текста. А «45 мин», «Day 3», «city to airport: » целым куском не
     бывают никогда — они собираются в коде вместе с числом или названием.

     Её требование 06.08.2026: «чтоб новый язык был больше не проблемой».
     Раньше в index.html стояло 47 развилок вида LANG!=='ru' ? английский :
     русский — и третий язык получил бы английский, потому что «не русский».
     Теперь в коде стоит cx('русская строка'), а перевод лежит здесь.

     ⚠️ ДОБАВИТЬ ЯЗЫК = ДОПИСАТЬ ЕГО ФАЙЛ lang-<код>.js. Код не трогается вовсе.
     Нет перевода — остаётся русский, как и везде: сайт не ломается.
     ══════════════════════════════════════════════════════════════════════ */
  var CODE = {};        /* куски для cx(): язык → { русский кусок: перевод } */

  /* ══════════════════════════════════════════════════════════════════════
     МНОЖЕСТВЕННОЕ ЧИСЛО — ПО ЯЗЫКАМ, А НЕ ОДНИМ АНГЛИЙСКИМ (шаг 2, 08.08.2026)

     Было: одна таблица PLURAL_EN, и любой не-русский язык получал английские
     слова. Для третьего языка это не подпорка, а мина: испанец увидел бы
     «2 places» посреди испанской фразы, и починить это можно было бы только
     правкой движка.

     Стало: у каждого языка своя запись — свои слова и СВОЁ ПРАВИЛО ВЫБОРА
     формы. Правило языка живёт вместе с его словарём, потому что оно и есть
     часть языка: в английском форм две, в русском три, в польском тоже три,
     но выбираются иначе.

     ⚠️ Ключ — русская тройка форм, как её пишет движок: он не знает языков.
     Нет записи для языка — цепочка язык → английский → русский, как везде.
     ══════════════════════════════════════════════════════════════════════ */
  var PLURAL = {};      /* язык → { pick: правило выбора формы, w: слова } */

  /* ══════════════════════════════════════════════════════════════════════
     ЯЗЫК ЗНАЕТ СВОЙ КАЛЕНДАРЬ (шаг 2 плана, 08.08.2026)

     Было: месяцы и дни недели лежали в index.html двумя парами массивов
     (MONTHS/WD по-русски, MONTHS_EN/WD_EN по-английски), а порядок слов в дате
     выбирала развилка LANG!=='ru'. Для третьего языка это тупик: испанец
     получил бы английские месяцы просто потому, что он «не русский», и
     починить это можно было бы только правкой index.html — то есть нарушением
     правила 22б.

     Стало: у каждого языка своя запись — названия месяцев, дни недели, знак
     дробной части и ОБРАЗЦЫ ДАТ. Образец — строка с метками, поэтому порядок
     слов у каждого языка свой, а движка это не касается:
        ru: '{d} {mon}'  →  «20 сентября»
        en: '{mon} {d}'  →  «September 20»

     ⚠️ Добавить язык = дописать сюда его запись. index.html не трогается.
     Нет записи — цепочка язык → английский → русский, как у словаря.
     ══════════════════════════════════════════════════════════════════════ */
  var LOCALE = {

    ru: {
      nm: 'Русский',                 /* как язык называется на самом себе */
      /* родительный падеж — он нужен датам: «7 августа» */
      mon: ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
        'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'],
      /* именительный — для галочки и названия поездки: «Когда: август» */
      monNm: ['январь', 'февраль', 'март', 'апрель', 'май', 'июнь',
        'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь'],
      /* короткий — «7 авг». Отрезан от родительного, поэтому «7 мая», а не «7 май» */
      monS: ['янв', 'фев', 'мар', 'апр', 'мая', 'июн',
        'июл', 'авг', 'сен', 'окт', 'ноя', 'дек'],
      /* короткий именительный — для выбора месяца в анкете: «май», не «мая» */
      monNmS: ['янв', 'фев', 'мар', 'апр', 'май', 'июн',
        'июл', 'авг', 'сен', 'окт', 'ноя', 'дек'],
      wd: ['вс', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб'],
      w1: 1,                         /* неделя начинается с понедельника */
      dec: ',',                      /* «10,8 км» */
      numTag: 'ru-RU',               /* как язык пишет числа: 10 800 */
      date: {
        full: '{wd}, {d} {mon}',     /* вс, 20 сентября */
        long: '{d} {mon}',           /* 20 сентября */
        short: '{d} {monS}',         /* 20 сен */
        span: '{d1}–{d2} {mon} {y}', /* 18–23 сентября 2026 */
        spanS: '{d1}–{d2} {monS}'    /* 7–10 авг */
      }
    }
    /* календарь остальных языков — в их файлах lang-<код>.js */

  };

  /* ⚠️ ЗАПАСНОЙ ЯЗЫК — ЦЕПОЧКА, А НЕ ОБРЫВ. Находка 07.08.2026 (шаг 0 плана).
     Раньше было так: нет перевода — отдаём русский. Для английского это верно
     (других языков не было), но испанец на испанской странице увидел бы РУССКИЙ
     текст в дырке словаря. Русский он не прочитает вовсе; английский — почти
     наверняка, раз ищет поездку.
     Поэтому цепочка: свой язык → английский → русский. Английский у нас полный,
     значит дырка нового языка закрывается понятным текстом, а не кириллицей. */
  function chain(lang) {
    return lang === 'en' ? ['en'] : [lang, 'en'];
  }

  function look(tbl, s, lang) {
    var ch = chain(lang);
    for (var i = 0; i < ch.length; i++) {
      var d = tbl[ch[i]];
      if (d && Object.prototype.hasOwnProperty.call(d, s)) return d[s];
    }
    return s;                       /* последнее звено цепочки — русский оригинал */
  }

  function t(s, lang) {
    if (!s || lang === 'ru' || !lang) return s;
    return look(DICT, s, lang);
  }

  /* кусок для кода: та же цепочка язык → английский → русский */
  function c(s, lang) {
    if (!s || lang === 'ru' || !lang) return s;
    return look(CODE, s, lang);
  }

  function plural(n, a, b, c, lang) {
    if (lang && lang !== 'ru') {
      /* та же цепочка, что у t(): нет своих форм — берём английские, а не
         русские. «2 точки» посреди испанской фразы читается хуже, чем «2 places».
         ⚠️ Правило выбора формы берём У ТОГО ЖЕ ЯЗЫКА, чьи слова взяли: в
         английском форм две, в другом языке их может быть три. */
      var key = a + '|' + b + '|' + c, ch = chain(lang);
      for (var i = 0; i < ch.length; i++) {
        var p = PLURAL[ch[i]], f = p && p.w && p.w[key];
        if (f) return f[(p.pick ? p.pick(n) : (n === 1 ? 0 : 1))] || f[f.length - 1];
      }
    }
    var x = n % 10, y = n % 100;
    if (x === 1 && y !== 11) return a;
    if (x >= 2 && x <= 4 && (y < 10 || y >= 20)) return b;
    return c;
  }

  /* ── КАЛЕНДАРЬ ЯЗЫКА ──
     Отдаёт запись языка по той же цепочке, что и словарь: свой язык →
     английский → русский. Русская запись есть всегда, поэтому пустого ответа
     не бывает и дата не может пропасть с экрана. */
  function loc(lang) {
    var ch = chain(lang || 'ru');
    for (var i = 0; i < ch.length; i++) if (LOCALE[ch[i]]) return LOCALE[ch[i]];
    return LOCALE.ru;
  }

  /* ── ДАТА ПО ОБРАЗЦУ ЯЗЫКА ──
     kind — какой образец брать: full / long / short / span / spanS.
     a, b — обычные даты (b нужна только для отрезка «18–23 сентября»).

     ⚠️ У ОТРЕЗКА МЕСЯЦ БЕРЁТСЯ ПО ВТОРОЙ ДАТЕ — так было и раньше в span2():
     «29 июля–2 августа» пишем месяцем конца. Внутри одного месяца разницы нет. */
  function date(kind, a, b, lang) {
    if (!a) return '';
    var L = loc(lang), pat = (L.date && L.date[kind]) || (LOCALE.ru.date[kind] || '');
    var span = kind.indexOf('span') === 0, m = (span && b ? b : a).getMonth();
    var v = {
      '{wd}': L.wd[a.getDay()],
      '{mon}': L.mon[m],
      '{monS}': L.monS[m],
      '{monNm}': L.monNm[m],
      '{d}': a.getDate(),
      '{d1}': a.getDate(),
      '{d2}': (b || a).getDate(),
      '{y}': (span && b ? b : a).getFullYear()
    };
    /* ⚠️ В метке бывает цифра — {d1}, {d2}. Без неё в образце отрезка
       оставались сами метки: «{d1}–{d2} сентября». Поймано первым же прогоном. */
    return pat.replace(/\{[a-zA-Z]+[0-9]*\}/g, function (k) {
      return v[k] === undefined ? k : String(v[k]);
    });
  }

  /* название месяца по номеру: 'nm' — именительный («август»), 'nms' — короткий
     именительный («май»), 's' — короткий для даты («мая»), иначе родительный */
  function month(i, how, lang) {
    if (i == null) return '';
    var L = loc(lang);
    var a = how === 's' ? L.monS : how === 'nms' ? (L.monNmS || L.monS)
      : how === 'nm' ? L.monNm : L.mon;
    return (a && a[i]) || '';
  }

  /* знак дробной части: «10,8 км» по-русски, «10.8 km» по-английски */
  function dec(lang) { return loc(lang).dec || '.'; }

  /* сколько уже переведено — чтобы видеть движение, а не гадать */
  function stats(lang) {
    var d = DICT[lang] || {};
    return { lang: lang, done: Object.keys(d).length };
  }

  /* ── ЯЗЫК ПРИЕХАЛ: КЛАДЁМ ЕГО НА МЕСТО ──
     ⚠️ Не заменяем таблицу, а ДОПИСЫВАЕМ в неё. Текст маршрута (trip-…-en.js)
     подмешивается в тот же DICT[язык], и порядок загрузки не гарантирован —
     заменой мы бы молча стёрли уже подмешанное. */
  function add(lang, pack) {
    if (!lang || !pack) return false;
    if (pack.DICT) DICT[lang] = mix(DICT[lang], pack.DICT);
    if (pack.CODE) CODE[lang] = mix(CODE[lang], pack.CODE);
    if (pack.PLURAL) PLURAL[lang] = pack.PLURAL;
    if (pack.LOCALE) LOCALE[lang] = pack.LOCALE;
    return true;
  }
  function mix(dst, src) {
    dst = dst || {};
    for (var k in src) if (Object.prototype.hasOwnProperty.call(src, k)) dst[k] = src[k];
    return dst;
  }

  /* словарь приехал раньше нас и оставил себя на окне — подбираем */
  try {
    var waiting = root && root.__i18nPacks;
    if (waiting) for (var w in waiting) add(w, waiting[w]);
  } catch (e) { }

  /* ⚠️ В ТЕРМИНАЛЕ ЧИТАЕМ ВСЕ ЯЗЫКИ САМИ. Проверкам, таблице перевода и сборке
     /en/ нужен полный набор, а подставлять файлы тегами там некому. Список не
     помним — спрашиваем у папки (то же правило, что у i18n-check.js). */
  try {
    if (typeof module === 'object' && module.exports) {
      var fs = require('fs'), path = require('path');
      fs.readdirSync(__dirname).forEach(function (f) {
        var m = /^lang-([a-z]{2})\.js$/.exec(f);
        if (m) add(m[1], require(path.join(__dirname, f)));
      });
    }
  } catch (e) { }

  return {
    t: t, c: c, plural: plural, stats: stats, add: add,
    date: date, month: month, dec: dec, loc: loc,
    DICT: DICT, CODE: CODE, PLURAL: PLURAL, LOCALE: LOCALE
  };
}));
