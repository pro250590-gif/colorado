#!/usr/bin/env bash
# ==========================================================================
#  ВЫКЛАДКА САЙТА НА СВОЙ СЕРВЕР
#
#  Зачем. 06.08.2026 выкладка GitHub Pages встала: сборка проходила, а сама
#  публикация десять минут висела в очереди и отменялась по таймауту. Сайт
#  замер на версии десятичасовой давности. Её решение — выкладывать на свой
#  сервер, который у неё уже есть (там живёт Throughline API).
#
#  ⚠️ GITHUB МЫ НЕ БРОСАЕМ. Он остаётся хранилищем и историей: там больше
#  трёхсот сохранённых версий, любую можно вернуть. Меняется только то, КУДА
#  раскладываются файлы для посетителей.
#
#  ⚠️ ЧУЖОЕ НА СЕРВЕРЕ НЕ ТРОГАЕМ. Там уже работают Throughline API и бот.
#  Поэтому: своя папка /var/www/kolibripro, свой конфиг nginx, никаких правок
#  в чужих файлах. Её условие дословно: «чтобы ты не путал мои старые папки».
#
#  Что выкладывается: ровно то, что отдаётся посетителю, — тот же белый список,
#  что в .gitignore. Инструменты разработки (check-*.js, i18n-scan.js) на сервер
#  не едут: они там не нужны и только мешали бы.
#
#  ⚠️ ПЕРЕД ОТПРАВКОЙ РАБОТАЮТ ВОРОТА (08.08.2026, шаг 3 плана). Три проверки —
#  check-ship.js, i18n-check.js, i18n-check-trip.js — должны пройти, иначе на
#  сервер не уходит ничего. Смысл: условия выкладки перестали быть записками,
#  которые надо помнить, и стали устройством. Подробности — в check-ship.js.
#
#  Запуск:  bash deploy.sh          — выложить
#           bash deploy.sh --check  — показать, что поедет, и прогнать ворота
# ==========================================================================
set -euo pipefail

SRV=root@167.99.213.122
KEY=~/.ssh/tvbot_ed25519
DST=/var/www/kolibripro
HERE="$(cd "$(dirname "$0")" && pwd)"

cd "$HERE"

# ⚠️ ВЫКЛАДЫВАЕМ НЕ ВСЁ, ЧТО В GIT. В репозиторий попадают и наши инструменты
# (check-*.js, i18n-scan.js, ROUTE-RULES.md) — на GitHub Pages они лежали зря,
# и повторять это не будем: посетителю они не нужны, а лишний файл на сервере
# однажды кто-нибудь откроет.
# Список собран по тому, что страница РЕАЛЬНО грузит: проверено грепом по
# index.html — теги <script src=...>, подгрузка airports.js из кода, картинки.
# ⚠️ Папка картинок задаётся ОТДЕЛЬНЫМ правилом. Первый вариант был
# '…|img/|CNAME)$' — и якорь конца строки съел все картинки: он требовал, чтобы
# строка была ровно «img/», а в списке они вида «img/hero-w.webp». Уехало 17
# файлов вместо 552, и скрипт при этом отчитался «Готово».
# ⚠️ ЯЗЫКИ ЗАДАНЫ ОБРАЗЦОМ, А НЕ ПЕРЕЧИСЛЕНИЕМ (08.08.2026, шаг 2 плана).
# Было 'en/index\.html' — ровно один язык. Добавили бы испанский, и /es/ просто
# не уехал бы на сервер: сборка прошла, deploy отчитался «Готово», а страницы
# нет. Тот же сорт тихой поломки, что и с картинками выше. Теперь берём любую
# двухбуквенную папку и любой словарь lang-<код>.js.
site_files(){
  git ls-files | grep -E '^(index\.html|[a-z]{2}/index\.html|i18n\.js|lang-[a-z]{2}\.js|day-math\.js|open-hours\.js|constructor\.js|airports\.js|trip-[a-z0-9-]+\.js|CNAME|sitemap\.xml|robots\.txt)$|^img/'
}
FILES=$(site_files)

if [ "${1:-}" = "--check" ]; then
  echo "Поедет файлов: $(echo "$FILES" | wc -l)"
  echo "$FILES" | head -20
  echo "..."
  echo ""
  node check-ship.js
  exit $?
fi

# Языковые копии собираем перед отправкой: иначе на /en/ уедет вчерашняя версия.
# ⚠️ ЗДЕСЬ Я УЖЕ ОШИБЛАСЬ, И ОШИБКА БЫЛА ТИХОЙ: пересобрав языковые копии, я
# перечитывала список ЦЕЛИКОМ (git ls-files) и теряла фильтр — на сервер уехали
# все 574 файла вместо 552, вместе с нашими инструментами. Скрипт при этом
# отработал «успешно». Поэтому список всегда берём одной функцией.
if [ -f build-langs.js ]; then
  node build-langs.js >/dev/null
  FILES=$(site_files)
fi

# ⚠️ ВОРОТА. Раньше условия выкладки («проверка должна давать ноль», «не забудьте
# добавить папку в .gitignore») жили в записках — то есть держались на том, что
# кто-то про них вспомнит. Защита, зависящая от чьего-то внимания, не работает:
# так `trip-paris-en.js` лежал на диске, а сайт отдавал 404, и так же тихо не
# уехал бы третий язык. Теперь условия проверяет машина, и без них выкладки нет.
#
#   check-ship.js       — всё ли, что нужно сайту, попало в историю (иначе 404);
#   i18n-check.js       — нет ли в движке русской строки без пути к переводу;
#   i18n-check-trip.js  — видит ли механизм весь текст маршрутов;
#   i18n-check-orig.js  — не уедет ли название в оригинале переводчику (правило 10).
#
# Медленные прогоны страницы (check-page.js) сюда не берём нарочно: минуты
# ожидания на каждой выкладке кончились бы тем, что ворота обошли бы стороной.
gate(){
  local bad=0
  for chk in check-ship.js i18n-check.js i18n-check-trip.js i18n-check-orig.js; do
    [ -f "$chk" ] || continue
    if ! out=$(node "$chk" 2>&1); then
      echo ""
      echo "⛔ ВЫКЛАДКА ОСТАНОВЛЕНА: $chk"
      echo "$out" | tail -30
      bad=1
    fi
  done
  [ "$bad" = 0 ] || { echo ""; echo "Ничего не отправлено. Почините и запустите снова."; exit 1; }
  echo "Ворота пройдены: файлы на месте, перевод полон."
}
gate

echo "Отправляю $(echo "$FILES" | wc -l) файлов…"

# ⚠️ ОТПРАВЛЯЕМ ЧЕРЕЗ tar, А НЕ rsync: rsync в Git Bash на Windows нет вовсе
# («command not found», проверено на первом же запуске). tar есть везде и
# делает то же самое одним потоком, без промежуточных файлов.
#
# Папку пересобираем заново — это замена rsync --delete: иначе файлы, которых у
# нас больше нет, останутся на сервере навсегда, и однажды кто-нибудь откроет
# забытую страницу. Трогаем ТОЛЬКО свою папку.
#
# ⚠️ Собираем рядом и подменяем целиком, а не пишем поверх: пока файлы
# распаковываются по одному, посетитель может поймать полусобранный сайт —
# новый index.html со старыми данными. Подмена мгновенная.
echo "$FILES" | tar czf - -T - | \
  ssh -i "$KEY" -o BatchMode=yes -o StrictHostKeyChecking=no "$SRV" \
  "set -e
   rm -rf $DST.new && mkdir -p $DST.new
   tar xzf - -C $DST.new
   chown -R nginx:nginx $DST.new
   find $DST.new -type d -exec chmod 755 {} +
   find $DST.new -type f -exec chmod 644 {} +
   rm -rf $DST.old
   [ -d $DST ] && mv $DST $DST.old || true
   mv $DST.new $DST
   rm -rf $DST.old
   # ⚠️ МЕТКУ SELinux СТАВИМ ПОСЛЕ ПОДМЕНЫ, И ЭТО ОБЯЗАТЕЛЬНО.
   # Постоянное правило (semanage fcontext) само по себе не помогает: папка
   # собирается рядом, под именем kolibripro.new, которое под правило не
   # подходит — она получает обычную метку и уносит её с собой при переименовании.
   # Результат: сайт отдаёт 403 при совершенно верных правах доступа.
   # Проверено на себе: первая выкладка после переезда легла именно так.
   restorecon -R $DST 2>/dev/null || true"

echo "Готово."
