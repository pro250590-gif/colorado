/* ==========================================================================
   ЧТО НЕ ПЕРЕВОДИТСЯ: НАЗВАНИЯ, АДРЕСА, ПОИСКОВЫЕ СТРОКИ (правило 10)

   Зеркало к `i18n-check.js`. Та проверка спрашивает «есть ли у русской строки
   путь к переводу». Эта спрашивает обратное: «а этот кусок точно не переведут
   те, кому не положено».

   ⚠️ ПЕРЕВОДЧИКОВ ДВА, И ВТОРОЙ НЕ НАШ.
   Первый — наш `applyDomT`: он заменит фразу, если она есть в словаре. Второй —
   встроенный переводчик Chrome и Edge, и мы сами оставили его кнопкой «глянуть
   быстро» для черновиков. Он переводит ВСЁ подряд и про наши правила не знает
   ничего. Без пометки он переведёт «Basilica di Sant'Ambrogio» и «Durango, CO» —
   то есть сломает ровно то, ради чего название написано в оригинале: человек
   должен ПОКАЗАТЬ его таксисту или на стойке (правило 10).

   Пометка одна на обоих: `data-noT translate="no"`. Ставит её функция `nmT()`
   в index.html — два атрибута, написанные руками в тридцати местах, разошлись
   бы в первый же день.

   ⚠️ ПОЧЕМУ ПРОВЕРКА НЕ РЕШАЕТ САМА, ЧТО ЯВЛЯЕТСЯ НАЗВАНИЕМ.
   Потому что по имени поля это не определить — на этом мы уже обожглись трижды
   (правило 22в). В поле `nm` лежит и «Castello Sforzesco», и «Колорадо, США» —
   название карточки на главной, которое переводить ОБЯЗАНЫ. Поэтому проверка
   требует не угадывания, а РЕШЕНИЯ: каждое место, где название попадает на
   страницу, либо обёрнуто в `nmT()`, либо названо здесь поимённо с причиной.
   Незнакомое место роняет проверку в ошибку — то же правило, что у списка
   подключённых файлов и у развилок по языку.

   Запуск:  node i18n-check-orig.js          — сводка
            node i18n-check-orig.js --list   — со всеми разобранными местами
   ========================================================================== */
const fs = require('fs'), path = require('path');
const DIR = __dirname;
const PAGE = path.join(DIR, 'index.html');

function stripComments(src) {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, m => m.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:'"\\])\/\/[^\n]*/g, (m, p) => p + m.slice(p.length).replace(/./g, ' '));
}
const RAW = fs.readFileSync(PAGE, 'utf8');
const src = stripComments(RAW);
const LINES = src.split('\n');

/* ── ГДЕ ИСКАТЬ ──────────────────────────────────────────────────────────────
   Поля и функции, из которых на страницу приходит имя места, города или
   поисковая строка. Список узкий нарочно: это не «всё, что называется nm», а
   те выражения, которые ДЕЙСТВИТЕЛЬНО отдают текст из данных поездки. */
const RX = /(?:[A-Za-z_$][\w$]*(?:\s*\([^()]*\))?(?:\.[A-Za-z_$][\w$]*)*)\.(?:nm|q)\b|\bbaseName\s*\(|\bhomeNm\s*\(/g;

/* ⚠️ `origHTML()` — вторая функция, которая ставит пометку сама (она рисует
   кнопку с оригинальным названием и копированием). Раз так, проверка обязана
   убедиться, что она это правда делает: иначе сорок мест окажутся «под защитой»,
   которой нет. Проверяем прямо тут, а не верим на слово. */
const origOK = /function origHTML\([\s\S]{0,600}?nmT\(/.test(src);

/* ── ЧЕЙ ЭТО АРГУМЕНТ ────────────────────────────────────────────────────────
   Идём от места находки влево, пропуская скобки парами и строки целиком, пока
   не упрёмся в незакрытую «(». Стоит перед ней имя — значит наше выражение
   уехало в вызов этой функции; не стоит — это просто скобка группировки, и
   надо идти дальше наружу. */
function enclosing(pos) {
  let i = pos - 1, depth = 0;
  while (i >= 0) {
    const c = src[i];
    if (c === ')' || c === ']' || c === '}') { depth++; i--; continue; }
    if (c === '(' || c === '[' || c === '{') {
      if (depth > 0) { depth--; i--; continue; }
      if (c !== '(') return { name: c === '[' ? '[…]' : '{…}', at: i };
      let j = i - 1; while (j >= 0 && /\s/.test(src[j])) j--;
      if (j >= 0 && /[\w$]/.test(src[j])) {
        let k = j; while (k >= 0 && /[\w$.]/.test(src[k])) k--;
        return { name: src.slice(k + 1, j + 1).replace(/^.*\./, ''), at: i };
      }
      i--; continue;                       /* скобка группировки — идём дальше */
    }
    if (c === '"' || c === "'") {          /* строку перепрыгиваем целиком */
      const q = c; let j = i - 1;
      while (j >= 0 && !(src[j] === q && src[j - 1] !== '\\')) j--;
      i = j - 1; continue;
    }
    i--;
  }
  return null;
}

/* обёртки, которые ничего не решают: заглядываем сквозь них дальше наружу */
const CLEAR = ['esc0', 'esc', 'shortName', 'String', 'trim', 'toLowerCase', 'split', 'replace'];

/* ── ЭТО ВООБЩЕ РАЗМЕТКА? ────────────────────────────────────────────────────
   Проверка следит за одним: за текстом, который встаёт МЕЖДУ ТЕГАМИ, — именно
   его увидит переводчик. Признак простой и тот же, что в i18n-check.js:
   ближайшая строка слева кончается на «>».

   ⚠️ ЧЕГО ЭТА МЕРА НЕ ВИДИТ — И ЭТО НАДО ГОВОРИТЬ ВСЛУХ. Значение, которое
   сначала кладут в переменную или в список, а показывают уже в другом месте,
   отсюда не проследить. Такие места проверка не считает ошибкой, но и не
   прячет: печатает их отдельным числом и по --list списком. Экран за ними
   смотрит второй прогон — «названия без пометки» в check-page.js. */
const LSTART = [];                          /* смещение начала каждой строки */
(function () { let o = 0; LINES.forEach(l => { LSTART.push(o); o += l.length + 1; }); })();
function leftLiteral(pos) {
  let ln = 0; while (ln + 1 < LSTART.length && LSTART[ln + 1] <= pos) ln++;
  for (let step = 0; step < 2 && ln - step >= 0; step++) {
    const left = step === 0 ? LINES[ln].slice(0, pos - LSTART[ln]) : LINES[ln - step];
    const lits = left.match(/'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"/g);
    if (lits && lits.length) return lits[lits.length - 1].slice(1, -1);
  }
  return null;
}
function inMarkup(pos) {
  let ln = 0; while (ln + 1 < LSTART.length && LSTART[ln + 1] <= pos) ln++;
  const codeLine = LINES[ln] || '';
  /* строка вообще собирает разметку? */
  if (!/'<|>'|<\/[a-z]/.test(codeLine)) return false;
  /* ⚠️ Текст между тегами или значение атрибута — решаем по тому, что БЛИЖЕ
     слева: закрытая скобка тега «>» или открытый атрибут «="». В атрибуте
     («href="'+…») человеку показывать нечего, а подписи title и aria-label
     переводит applyDomT своим проходом. Пометку туда ставить нельзя вовсе:
     span внутри значения атрибута — это сломанная разметка. */
  const left = codeLine.slice(0, pos - LSTART[ln]);
  return left.lastIndexOf('>') > Math.max(left.lastIndexOf('="'), left.lastIndexOf("='"));
}

/* ── РЕШЕНИЯ ПО МЕСТАМ, ГДЕ ИМЯ НЕ НАДО ПОМЕЧАТЬ ────────────────────────────
   Ключ — имя функции, в которую уезжает выражение. Значение — причина.
   Причина обязана объяснять, почему человек этого текста НЕ ВИДИТ либо почему
   его как раз надо переводить. «И так понятно» причиной не считается. */
const OK_CALL = {
  /* адрес ссылки: человек видит подпись, а не то, что внутри href */
  bookHotel: 'уезжает в адрес брони — человек этого текста не видит',
  hsData:    'данные для кнопки «искать в другом сервисе», лежат в data-атрибутах',
  gmSearch:  'поисковая строка Google Maps в адресе ссылки',
  gurl:      'адрес карточки места в Google Maps',
  mapURL:    'адрес карточки места в Google Maps (правило 10а)',
  transit:   'адрес расписания транспорта',
  geocode:   'просим у геокодера координату по названию — это запрос, а не текст',
  encodeURIComponent: 'кусок адреса',
  aff:       'партнёрская ссылка',

  /* сравнения и разбор: строка вообще не попадает на экран */
  test:      'разбор строки регуляркой, на экран не выходит',
  match:     'разбор строки, на экран не выходит',
  indexOf:   'сравнение, на экран не выходит',
  find:      'поиск по списку, на экран не выходит',
  filter:    'отбор по списку, на экран не выходит',
  some:      'сравнение по списку, на экран не выходит',
  push:      'складываем значение в список, показывать его будет другой код',
  RegExp:    'кусок регулярки',

  /* значение поля ввода: человек его правит сам, и это его собственный текст */
  esc:       'значение в поле ввода — человек его правит, переводить нельзя ни нам, ни браузеру'
};

/* Отдельные места, разобранные поимённо: ключ — кусок кода, по которому место
   узнаётся однозначно. Сюда попадает то, что НЕ является названием в оригинале
   и потому должно переводиться (правило 22в: решает не имя поля, а место). */
const OK_CODE = {
  "esc0(cat.nm": 'название карточки готового маршрута («Колорадо, США») — это наш текст, он переводится',
  "'<b>'+esc0(c.nm)+'</b>'": 'название карточки на витрине готовых маршрутов — наш текст, переводится',
  "lab(f.nm)": 'заголовок вопроса анкеты («куда едете?») — наш текст, переводится',
  "esc0(it?it.nm:'')": 'своя строка бюджета в поле ввода — человек её правит сам',
  "meta[k]&&meta[k].nm": 'название варианта дня («основной план») — наш текст, переводится',
  "(meta[k]&&meta[k].nm)": 'название варианта дня — наш текст, переводится',
  "esc0(p.nm+(p.sub?": 'подпись варианта дня на кнопке — наш текст, переводится',
  "'<b>'+cur.nm+'</b>": 'название варианта дня — наш текст, переводится',
  "s.nm+'</b><span>'+s.sub": 'название сервиса жилья в списке выбора (Booking, Airbnb) — латиница, переводчику там нечего делать',
  "nm:s.nm,q:s.nm+' '+c.q": 'собираем точку еды для карты — на экран её покажет другой код',
  "city:c.q||''": 'город кладём в данные, показывать будет другой код',
  "a.dest=a.onlyNm": 'собираем ответ анкеты для разбора, не для показа'
};

const marked = [], excused = [], bad = [], aside = [];
let m;
while ((m = RX.exec(src))) {
  const pos = m.index;
  const line = src.slice(0, pos).split('\n').length;
  const codeLine = (LINES[line - 1] || '').trim();
  const frag = src.slice(pos, pos + 60).split('\n')[0];
  /* объявление функции — не место показа */
  if (/^\s*function\s+$/.test(src.slice(Math.max(0, pos - 10), pos)) || /^\s*function\s/.test(codeLine)) continue;

  /* ⚠️ Поимённое решение сильнее всего остального — и узнаётся по КУСКУ КОДА
     в той же строке, а не по номеру строки: номера съезжают от любой правки
     выше, и список исключений начал бы врать молча. */
  const byCode = Object.keys(OK_CODE).filter(k => codeLine.indexOf(k) >= 0)[0];
  if (byCode) { excused.push({ line, frag, why: OK_CODE[byCode] }); continue; }

  /* чей это аргумент — заглядывая сквозь пустые обёртки */
  let e = enclosing(pos), guard = 0;
  while (e && CLEAR.indexOf(e.name) >= 0 && guard++ < 6) e = enclosing(e.at);

  if (e && e.name === 'nmT') { marked.push({ line, frag }); continue; }
  if (e && OK_CALL[e.name]) { excused.push({ line, frag, why: OK_CALL[e.name] }); continue; }

  if (!inMarkup(pos)) { aside.push({ line, frag, call: e ? e.name : '—', code: codeLine.slice(0, 130) }); continue; }
  bad.push({ line, frag, call: e ? e.name : 'напрямую в разметку', code: codeLine.slice(0, 150) });
}

/* ── пометка в самой разметке: оба атрибута всегда вместе ──────────────────
   Метка живёт в одной функции нарочно. Но если кто-то напишет data-noT руками
   и забудет translate="no" — браузерный переводчик всё равно доберётся до
   названия, а мы будем считать, что защитились. */
const halves = [];
LINES.forEach((ln, i) => {
  /* сам механизм ищет пометку селектором ('[data-noT]') — это не разметка */
  const put = ln.replace(/\[data-noT\]/g, '');
  const noT = /data-noT/.test(put), br = /translate="no"/.test(put);
  if (noT !== br) halves.push({ line: i + 1, code: ln.trim().slice(0, 120) });
});

console.log('НАЗВАНИЯ В ОРИГИНАЛЕ — ПОМЕТКА «НЕ ПЕРЕВОДИТЬ» (правило 10)\n');
console.log('  помечено nmT():               ' + marked.length);
console.log('  разобрано с причиной:         ' + excused.length);
if (process.argv.indexOf('--list') >= 0) {
  const byWhy = {};
  excused.forEach(x => (byWhy[x.why] = byWhy[x.why] || []).push(x));
  Object.keys(byWhy).sort((a, b) => byWhy[b].length - byWhy[a].length)
    .forEach(w => console.log('        · ' + String(byWhy[w].length).padStart(3) + '  ' + w));
}
/* ⚠️ Границу меры показываем числом, а не умалчиваем: это те места, где имя
   уезжает значением дальше в код, и до экрана проверка за ним не идёт. */
console.log('  уезжает значением в код:      ' + aside.length + '  (за ними следит check-page.js)');
if (process.argv.indexOf('--list') >= 0)
  aside.forEach(x => console.log('        · ' + String(x.line).padStart(6) + '  ' + x.code));
console.log('');
console.log('  ⛔ БЕЗ РЕШЕНИЯ (название уедет переводчику): ' + bad.length);
if (bad.length) {
  console.log('');
  bad.forEach(b => {
    console.log('   ' + String(b.line).padStart(6) + '  ' + b.frag);
    console.log('           уезжает в: ' + b.call);
    console.log('           ' + b.code);
  });
  console.log('');
  console.log('  Либо оберните название в nmT() — тогда его не тронут ни мы, ни браузер,');
  console.log('  либо назовите это место в i18n-check-orig.js и объясните, почему это не');
  console.log('  название в оригинале (правило 22в: решает место, а не имя поля).');
}
if (!origOK) {
  console.log('');
  console.log('  ⛔ origHTML() БОЛЬШЕ НЕ СТАВИТ ПОМЕТКУ. Эта функция рисует кнопку с');
  console.log('     оригинальным названием, и проверка считает такие места защищёнными.');
  console.log('     Верните nmT() внутрь origHTML() в index.html.');
}
if (halves.length) {
  console.log('');
  console.log('  ⛔ ПОМЕТКА НАПОЛОВИНУ: ' + halves.length + ' — есть один атрибут из двух');
  halves.forEach(h => console.log('   ' + String(h.line).padStart(6) + '  ' + h.code));
  console.log('  data-noT держит наш перевод, translate="no" — браузерный. Нужны оба.');
}
console.log('');
process.exit((bad.length || halves.length || !origOK) ? 1 : 0);
